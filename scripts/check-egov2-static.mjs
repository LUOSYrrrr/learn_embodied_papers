import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
import tables from '../content/egohumanoid-v2/tables.mjs';
const file='papers/egohumanoid-v2.html';
const hash=()=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const before=hash();
execFileSync(process.execPath,['scripts/build-egov2-deep-reading.mjs']);
const after=hash();
if(before!==after)throw Error('Build is not idempotent.');
const html=fs.readFileSync(file,'utf8');
for(let n=1;n<=9;n++)if(!html.includes(`data-formula="${n}"`)||!html.includes(`data-example="eq${n}"`))throw Error(`Missing equation ${n}`);
for(let n=1;n<=12;n++)if(!html.includes(`data-paper-table="${n}"`))throw Error(`Missing table ${n}`);
for(const t of tables)for(const part of t.tables)for(const row of part.rows)if(row.length!==part.head.length)throw Error(`Table ${t.n}: mismatched row`);
const base=pathToFileURL(path.resolve('papers')+path.sep).href;
const noScripts=html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'').replace('<head>',`<head><base href="${base}">`);
fs.writeFileSync('/tmp/egov2-without-page-scripts.html',noScripts);
console.log(JSON.stringify({idempotent:true,equations:9,originalFigures:10,tables:12,explanatoryDiagrams:2,htmlBytes:Buffer.byteLength(html),noScriptPreview:'/tmp/egov2-without-page-scripts.html'},null,2));
